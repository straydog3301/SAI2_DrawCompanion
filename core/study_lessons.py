def _lesson(id, skill, level, name, goal, focus, phases, mistakes, checks, refs, tools=(), look_for=''):
    return {
        'id': id, 'skill': skill, 'level': level, 'name': name,
        'goal': goal, 'focus': focus,
        'phases': [{'name': n, 'minutes': m, 'tip': t} for n, m, t in phases],
        'minutes': sum(m for _, m, _ in phases),
        'mistakes': list(mistakes), 'checks': list(checks),
        'refs': list(refs), 'tools': list(tools),
        'look_for': look_for or focus,
    }


