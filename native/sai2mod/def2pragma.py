"""Convert a proxy DLL's .def exports into MSVC #pragma linker directives.

MSVC's LINK rejects forwarder targets that carry a full path in an EXPORTS .def
(it tries to resolve them as local symbols -> LNK2001), but /export directives
accept them. build.bat force-includes the generated header (/FI) so sai2mod.c
re-exports every system entry point to the real DLL in System32.

Handles both .def styles in this folder:
  mscms:  Name=C:\\WINDOWS\\System32\\mscms.Func @ord        (unquoted, doubled \\)
  dwmapi: Name="C:\\WINDOWS\\System32\\dwmapi.Func" @ord [NONAME]  (quoted, single \\)
          __ordNNN="...dwmapi.#NNN" @NNN NONAME                (by-ordinal forward)

Usage: python def2pragma.py mscms  ->  writes mscms_exports.h
"""
import os
import re
import sys

# name = [optional "] target [optional "]  @ordinal  [NONAME]
LINE = re.compile(r'^\s*(\S+?)=(")?(.+?)(?(2)")\s+@(\d+)(\s+NONAME)?\s*$')


def convert(name: str, folder: str) -> str:
    out = [f'/* generated by def2pragma.py from {name}.def */']
    with open(os.path.join(folder, f'{name}.def'), encoding='ascii') as f:
        for line in f:
            if line.strip() in ('', 'EXPORTS') or line.startswith('LIBRARY'):
                continue
            m = LINE.match(line)
            if not m:
                continue
            export, _, target, ordinal, noname = m.groups()
            # Normalise however the .def escaped backslashes, then escape once for the C string.
            target = target.replace('\\\\', '\\').replace('\\', '\\\\')
            extra = ',NONAME' if noname else ''
            out.append(f'#pragma comment(linker, "/export:{export}={target},@{ordinal}{extra}")')
    path = os.path.join(folder, f'{name}_exports.h')
    with open(path, 'w', encoding='ascii') as f:
        f.write('\n'.join(out) + '\n')
    return path


if __name__ == '__main__':
    print(convert(sys.argv[1], os.path.dirname(os.path.abspath(__file__))))
